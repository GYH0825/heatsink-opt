# -*- coding: utf-8 -*-
"""散热器热-几何优化：物理常量、外形尺寸、约束与参数空间。

单位一律使用 SI（米 / 摄氏度 / 瓦），只在打印和绘图时换算成毫米。

二维截面沿 z 方向等截面拉伸：
    截面内做二维稳态热传导求解，z 方向只做面积/体积按 DEPTH 的线性缩放。
"""

# ---------------------------------------------------------------- 物理环境
K_ALUMINUM = 200.0       # W/(m·K)   铝合金导热系数
H_CONVECTION = 12.0      # W/(m²·K)  自然对流换热系数（无风扇）
T_AMBIENT = 25.0         # °C        环境温度
CHIP_POWER = 20.0        # W         芯片总发热功率（均匀施加于基板底面）
RHO_ALUMINUM = 2700.0    # kg/m³     铝合金密度

# ---------------------------------------------------------------- 散热器外形
WIDTH = 0.060            # m  截面 x 方向宽度
HEIGHT = 0.050           # m  截面 y 方向高度（基板 + 翅片的最大总高）
DEPTH = 0.060            # m  z 方向深度

# ---------------------------------------------------------------- 网格
NX, NY = 120, 100        # 节点数；dx = dy = 0.5 mm
                         # 翅片最小厚度取 2 mm = 4 个网格，避免薄壁被网格锯齿化

# ---------------------------------------------------------------- 设计约束
T_MAX_LIMIT = 85.0       # °C   芯片最高结温上限
MASS_LIMIT = 0.150       # kg   散热器质量上限（材料成本）
MIN_GAP = 0.002          # m    最小翅片间隙（挤压/铣削可制造性下限）

# ---------------------------------------------------------------- 参数空间
# (名称, 下限, 上限, 是否整数)
PARAM_SPEC = (
    ("n_fins",         3,     15,    True),
    ("fin_height",     0.010, 0.040, False),
    ("fin_thickness",  0.002, 0.006, False),
    ("base_thickness", 0.002, 0.010, False),
)

# 参数中文名（绘图与日志用）
PARAM_LABEL = {
    "n_fins": "翅片数量",
    "fin_height": "翅片高度",
    "fin_thickness": "翅片厚度",
    "base_thickness": "基板厚度",
}


def flux_per_depth():
    """单位深度上的线功率密度 q' [W/m]。"""
    return CHIP_POWER / DEPTH
